import os
import joblib
import pandas as pd
from typing import List, Dict, Any
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline

MODEL_PATH = os.path.join(os.path.dirname(__file__), "model.joblib")

_MODEL_PIPELINE = None

def get_or_load_model():
    global _MODEL_PIPELINE
    if _MODEL_PIPELINE is not None:
        return _MODEL_PIPELINE

    if os.path.exists(MODEL_PATH):
        try:
            _MODEL_PIPELINE = joblib.load(MODEL_PATH)
            print(f"[ML Infer] Successfully loaded trained model from {MODEL_PATH}")
            return _MODEL_PIPELINE
        except Exception as e:
            print(f"[ML Infer] Error loading joblib model: {e}. Rebuilding fallback baseline.")

    # Fallback Baseline Model Initialization
    print("[ML Infer] Creating baseline fall-back sentiment model...")
    seed_headlines = [
        "Stock surges on record quarterly earnings beating consensus estimates",
        "Company reports strong revenue growth and expanded margins",
        "Bullish outlook as analysts upgrade stock price target",
        "Shares plunge following disappointing earnings release and lowered guidance",
        "Company faces regulatory antitrust lawsuit investigation and fines",
        "Revenue drops as consumer demand weakens across key product lines"
    ]
    seed_labels = [1, 1, 1, 0, 0, 0]

    pipeline = Pipeline([
        ("tfidf", TfidfVectorizer(stop_words="english", ngram_range=(1, 2))),
        ("clf", LogisticRegression())
    ])
    pipeline.fit(seed_headlines, seed_labels)
    _MODEL_PIPELINE = pipeline
    return _MODEL_PIPELINE

HONESTY_DISCLAIMER = (
    "Headline sentiment is a weak, noisy indicator of next-day price movement. "
    "This output is generated by a self-trained scikit-learn model for portfolio/educational "
    "demonstration purposes only, NOT financial or investment advice."
)

def predict_stock_sentiment(ticker: str, headlines: List[Dict[str, Any]]) -> Dict[str, Any]:
    ticker = ticker.upper()
    if not headlines:
        return {
            "ticker": ticker,
            "sentiment": "neutral",
            "confidence": 0.50,
            "headline_count": 0,
            "up_probability": 0.50,
            "summary_text": "No recent headlines available for sentiment scoring.",
            "disclaimer": HONESTY_DISCLAIMER
        }

    pipeline = get_or_load_model()
    texts = [h.get("title", "") for h in headlines if h.get("title")]

    if not texts:
        return {
            "ticker": ticker,
            "sentiment": "neutral",
            "confidence": 0.50,
            "headline_count": 0,
            "up_probability": 0.50,
            "summary_text": "No headline text extracted.",
            "disclaimer": HONESTY_DISCLAIMER
        }

    try:
        probs = pipeline.predict_proba(texts)
        up_probs = probs[:, 1]
        avg_up_prob = float(up_probs.mean())
    except Exception as e:
        print(f"[ML Infer] Prediction error: {e}")
        avg_up_prob = 0.50

    if avg_up_prob >= 0.55:
        sentiment = "bullish"
        confidence = round(avg_up_prob, 2)
        lean_desc = f"{int(avg_up_prob * 100)}% of headline signals associate with upward movement"
    elif avg_up_prob <= 0.45:
        sentiment = "bearish"
        confidence = round(1.0 - avg_up_prob, 2)
        lean_desc = f"{int((1.0 - avg_up_prob) * 100)}% of headline signals associate with downward movement"
    else:
        sentiment = "neutral"
        confidence = round(1.0 - abs(avg_up_prob - 0.5), 2)
        lean_desc = f"Balanced signals ({int(avg_up_prob * 100)}% upward lean)"

    return {
        "ticker": ticker,
        "sentiment": sentiment,
        "confidence": confidence,
        "headline_count": len(texts),
        "up_probability": round(avg_up_prob, 2),
        "summary_text": lean_desc,
        "disclaimer": HONESTY_DISCLAIMER
    }
